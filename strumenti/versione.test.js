/*
 * La versione in un posto solo, provata sui due lockfile.
 *
 * `versione.js` girava solo come script, e controllava tre file su cinque: il
 * `Cargo.lock` e il `package-lock.json` restavano indietro dopo `version:set`, e
 * se ne accorgeva la CI minuti dopo (`cargo clippy --locked`: «the lock file
 * needs to be updated»), o nessuno (la versione della radice del lockfile di
 * npm). Qui le due metà — il controllo e la riscrittura — si provano su testi
 * finti, e poi sul repository vero.
 *
 *   node --test "strumenti/*.test.js"
 */
const test = require("node:test");
const assert = require("node:assert/strict");

const { discordanze, riscrivi, numeroAmmesso, codiceAndroid, leggiTutto } = require("./versione.js");

/** Un repository finto, piccolo ma con la forma vera dei cinque file. */
function repositoryFinto(v = "3.2.0") {
  return {
    cargoToml: [
      "[workspace]",
      "members = [",
      '    "core/rymembra-domain",',
      '    "apps/desktop/src-tauri",',
      "]",
      "",
      "[workspace.package]",
      `version = "${v}"`,
      'edition = "2024"',
      "",
      "[workspace.dependencies]",
      'serde = { version = "1.0" }',
      "",
    ].join("\n"),
    manifestiDeiMembri: {
      "core/rymembra-domain/Cargo.toml": '[package]\nname = "rymembra-domain"\nversion.workspace = true\n',
      "apps/desktop/src-tauri/Cargo.toml": '[package]\nname = "rymembra-desktop"\nversion.workspace = true\n',
    },
    packageJson: `{\n  "name": "rymembra-desktop",\n  "private": true,\n  "version": "${v}",\n  "type": "module"\n}\n`,
    tauriConf: `{\n  "productName": "Rymembra",\n  "version": "${v}",\n  "identifier": "x"\n}\n`,
    cargoLock: [
      "# This file is automatically @generated by Cargo.",
      "version = 4",
      "",
      "[[package]]",
      'name = "rymembra-desktop"',
      `version = "${v}"`,
      "dependencies = [",
      ' "rymembra-domain",',
      "]",
      "",
      "[[package]]",
      'name = "rymembra-domain"',
      `version = "${v}"`,
      "",
      // Un crate del registro con lo stesso numero: non è nostro, non si tocca.
      "[[package]]",
      'name = "qualcosa"',
      `version = "${v}"`,
      'source = "registry+https://github.com/rust-lang/crates.io-index"',
      'checksum = "abc"',
      "",
    ].join("\n"),
    packageLock: [
      "{",
      '  "name": "rymembra-desktop",',
      `  "version": "${v}",`,
      '  "lockfileVersion": 3,',
      '  "requires": true,',
      '  "packages": {',
      '    "": {',
      '      "name": "rymembra-desktop",',
      `      "version": "${v}",`,
      '      "dependencies": {',
      '        "react": "^19.3.0"',
      "      }",
      "    },",
      '    "node_modules/react": {',
      `      "version": "${v}",`,
      '      "license": "MIT"',
      "    }",
      "  }",
      "}",
      "",
    ].join("\n"),
  };
}

test("un repository allineato non ha discordanze", () => {
  assert.deepEqual(discordanze(repositoryFinto()), []);
});

test("il controllo vede il Cargo.lock rimasto indietro", () => {
  const r = repositoryFinto("3.3.0");
  r.cargoLock = repositoryFinto("3.2.0").cargoLock;
  const d = discordanze(r);
  assert.ok(d.some((x) => /Cargo\.lock/.test(x) && /rymembra-domain/.test(x)), d.join("\n"));
});

test("il controllo vede il package-lock.json rimasto indietro, alla radice e in packages[\"\"]", () => {
  const r = repositoryFinto("3.3.0");
  r.packageLock = repositoryFinto("3.2.0").packageLock;
  const d = discordanze(r);
  assert.equal(d.filter((x) => /package-lock\.json/.test(x)).length, 2, d.join("\n"));
});

test("un membro del workspace che manca nel Cargo.lock si vede", () => {
  const r = repositoryFinto();
  r.manifestiDeiMembri["core/rymembra-nuovo/Cargo.toml"] = '[package]\nname = "rymembra-nuovo"\nversion.workspace = true\n';
  r.cargoToml = r.cargoToml.replace('    "apps/desktop/src-tauri",', '    "apps/desktop/src-tauri",\n    "core/rymembra-nuovo",');
  assert.ok(discordanze(r).some((x) => /rymembra-nuovo/.test(x)));
});

test("un membro con una versione sua si vede", () => {
  const r = repositoryFinto();
  r.manifestiDeiMembri["core/rymembra-domain/Cargo.toml"] = '[package]\nname = "rymembra-domain"\nversion = "0.1.0"\n';
  assert.ok(discordanze(r).some((x) => /version\.workspace/.test(x)));
});

test("version:set riscrive anche i due lockfile, e soltanto le righe della versione", () => {
  const prima = repositoryFinto("3.2.0");
  const dopo = riscrivi(prima, "3.3.0");
  assert.deepEqual(discordanze(dopo), []);
  const cambiate = (a, b) => a.split("\n").filter((r, i) => r !== b.split("\n")[i]).length;
  assert.equal(cambiate(prima.cargoLock, dopo.cargoLock), 2);
  assert.equal(cambiate(prima.packageLock, dopo.packageLock), 2);
  assert.equal(cambiate(prima.cargoToml, dopo.cargoToml), 1);
  // Il crate del registro e il pacchetto npm con lo stesso numero restano com'erano.
  assert.match(dopo.cargoLock, /name = "qualcosa"\nversion = "3\.2\.0"/);
  assert.match(dopo.packageLock, /"node_modules\/react": \{\n {6}"version": "3\.2\.0"/);
});

test("i numeri che il versionCode di Android e l'MSIX non reggono si rifiutano", () => {
  assert.equal(numeroAmmesso("3.2.1"), null);
  assert.equal(codiceAndroid("3.2.1"), 3002001);
  assert.equal(codiceAndroid("3.3.0"), 3003000);
  // 3.1000.0 darebbe 4000000, lo stesso codice della 4.0.0.
  assert.match(numeroAmmesso("3.1000.0"), /999/);
  assert.match(numeroAmmesso("3.2.1000"), /999/);
  assert.match(numeroAmmesso("2101.0.0"), /versionCode/);
  assert.match(numeroAmmesso("3.2.1-rc.1"), /tre numeri/);
  assert.match(numeroAmmesso("3.2"), /tre numeri/);
});

test("il repository vero è allineato in tutti e cinque i file", () => {
  assert.deepEqual(discordanze(leggiTutto()), []);
});
